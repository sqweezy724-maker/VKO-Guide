export const getSeasonalPlace = (season: "winter" | "summer"): Place => {
  const seasonal = places.filter(p => p.season === season || p.season === "all");
  return seasonal[0];
};

export const getNearbyPlace = (lat: number, lng: number): Place => {
  let nearest = places[0];
  let minDist = Infinity;
  for (const p of places) {
    const dist = Math.sqrt((p.lat - lat) ** 2 + (p.lng - lng) ** 2);
    if (dist < minDist) {
      minDist = dist;
      nearest = p;
    }
  }
  return nearest;
};
